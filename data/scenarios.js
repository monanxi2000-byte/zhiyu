/** 字符二元组。 */
function bigrams(s) {
  const out = [];
  for (let i = 0; i + 1 < s.length; i++) out.push(s.slice(i, i + 2));
  return out;
}

/** 泛化二元组黑名单：这些字对本身不构成领域信号，不计入重叠得分。 */
const STOP_BIGRAMS = new Set([
  '入门', '基础', '方法', '技巧', '学习', '知识', '指南', '教程', '经验',
  '提升', '提高', '能力', '攻略', '课程', '书籍', '问题', '适合', '新手',
  '怎样', '如何', '怎么', '什么', '为什么', '有没有', '需要', '可以',
  '准备', '开始', '阶段', '时间', '计划', '避坑', '分享', '推荐', '干货',
  '快速', '高效', '正确', '常见', '几个', '一条', '路径', '路线', '职业',
]);

/**
 * 场景匹配：
 *  · 子串命中（关键词包含于话题 / 话题包含于关键词）→ 高权重
 *  · 二元组重叠（需 ≥2 个不同二元组）→ 辅助，避免「入门」「学习」等
 *    泛词造成误匹配（如「考古学入门」不再误命中「编程入门」）。
 */
function matchScenario(topic) {
  const t = String(topic || '').toLowerCase();
  const tb = new Set(bigrams(t));
  let best = null;
  let bestScore = 0;
  for (const key of Object.keys(S)) {
    const sc = S[key];
    let score = 0;
    const overlap = new Set();
    for (const kw of sc.keywords) {
      const k = kw.toLowerCase();
      if (k.length < 2) continue;
      if (t.includes(k) || k.includes(t)) {
        score += k.length * 3;
        continue;
      }
      for (const b of bigrams(k)) if (tb.has(b) && !STOP_BIGRAMS.has(b)) overlap.add(b);
    }
    if (overlap.size >= 2) score += overlap.size;
    if (score > bestScore) {
      bestScore = score;
      best = sc;
    }
  }
  return best || null;
}

function getAllScenarios() {
  return Object.values(S).map(({ id, name, emoji, tagline, audience, keywords }) => ({ id, name, emoji, tagline, audience, keywords }));
}

module.exports = { scenarios: S, GENERIC, matchScenario, getAllScenarios };

